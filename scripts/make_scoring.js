function table(widths, rows, leftCols = [0]) {
  return new Table({
    columnWidths: widths,
    width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA },
    rows: rows.map((r, ri) => new TableRow({
      tableHeader: ri === 0,
      children: r.map((v, ci) => new TableCell({
        width: { size: widths[ci], type: WidthType.DXA },
        margins: { top: 50, bottom: 50, left: 90, right: 90 },
        children: [new Paragraph({
          alignment: ri === 0 ? AlignmentType.CENTER : (leftCols.includes(ci) ? AlignmentType.LEFT : AlignmentType.CENTER),
          spacing: { line: 240, after: 0 },
          children: [run(String(v), { size: SZ_T, bold: ri === 0 })],
        })],
      })),
    })),
  });
}

